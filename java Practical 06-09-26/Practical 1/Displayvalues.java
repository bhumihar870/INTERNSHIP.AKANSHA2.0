class Displayvalues {

    public static void main(String[] args) {
        int a = 10;
        float b = 2.5f;
        double c = 25.21544775;
        char d = 'D';

        System.out.println("int value: " + a);
        System.out.println("float value: " + b);
        System.out.println("double value: " + c);
        System.out.println("char value: " + d);
    }
}