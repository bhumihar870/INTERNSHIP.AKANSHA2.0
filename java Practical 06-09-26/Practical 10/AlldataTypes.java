public class AlldataTypes {
    public static void main(String[] args) {
        // Declaring and initializing all 8 primitive data types
        byte age = 25;
        short year = 2026;
        int distanceInMeters = 75840;
        long worldPopulation = 8000000000L;
        float temperature = 36.6f;
        double pi = 3.14159265359;
        char grade = 'A';
        boolean isJavaFun = true;

        // Displaying the value of each variable
        System.out.println("byte value: " + age);
        System.out.println("short value: " + year);
        System.out.println("int value: " + distanceInMeters);
        System.out.println("long value: " + worldPopulation);
        System.out.println("float value: " + temperature);
        System.out.println("double value: " + pi);
        System.out.println("char value: " + grade);
        System.out.println("boolean value: " + isJavaFun);
    }
}
